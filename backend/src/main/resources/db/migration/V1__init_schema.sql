-- Начальная схема оргструктуры. Подробное описание — docs/DB.md.

-- Подразделения образуют дерево через parent_id (список смежности).
create table department (
    id               bigint generated by default as identity primary key,
    code             text   not null unique,
    name             text   not null,
    description      text,
    parent_id        bigint references department (id),
    head_employee_id bigint, -- внешний ключ добавим ниже, после создания employee
    constraint ck_department_not_own_parent check (parent_id is null or parent_id <> id)
);

-- Корневое подразделение ровно одно: индекс по константе допускает одну строку с parent_id is null.
create unique index ux_department_single_root on department ((1)) where parent_id is null;
create index ix_department_parent on department (parent_id);

-- Сотрудник закреплён ровно за одним (основным) подразделением.
create table employee (
    id            bigint generated by default as identity primary key,
    full_name     text   not null,
    position      text   not null,
    email         text   not null unique,
    phone         text,
    department_id bigint not null references department (id)
);
create index ix_employee_department on employee (department_id);

-- Руководитель подразделения — сотрудник (цикл ссылок department <-> employee разрешён осознанно).
alter table department
    add constraint fk_department_head foreign key (head_employee_id) references employee (id);

-- Подчинение: LINE — линейное (ровно одно у каждого, кроме главы), DOTTED — матричное (0..N).
create table reporting_line (
    id          bigint generated by default as identity primary key,
    employee_id bigint not null references employee (id),
    manager_id  bigint not null references employee (id),
    line_type   text   not null,
    comment     text,
    constraint ck_reporting_type check (line_type in ('LINE', 'DOTTED')),
    constraint ck_reporting_not_self check (employee_id <> manager_id),
    constraint uq_reporting_pair unique (employee_id, manager_id)
);
-- Не более одного линейного руководителя на сотрудника.
create unique index ux_reporting_single_line on reporting_line (employee_id) where line_type = 'LINE';
create index ix_reporting_manager on reporting_line (manager_id);

-- Задачи (что делает) и зоны ответственности (за что отвечает).
create table assignment (
    id          bigint generated by default as identity primary key,
    employee_id bigint not null references employee (id),
    kind        text   not null,
    title       text   not null,
    description text,
    sort_order  int    not null default 0,
    constraint ck_assignment_kind check (kind in ('TASK', 'RESPONSIBILITY'))
);
create index ix_assignment_employee on assignment (employee_id);
